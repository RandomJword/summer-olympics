  const GW = 7, GH = 8, ADV = 8;
  const GLYPHS = {};
  for (const k in RAW) GLYPHS[k] = RAW[k].replace(/ /g, '');

  const cache = new Map();
  function glyphCanvas(ch, color) {
    const key = ch + color;
    let c = cache.get(key);
    if (c) return c;
    const bits = GLYPHS[ch] || GLYPHS['?'];
    c = document.createElement('canvas');
    c.width = GW; c.height = GH;
    const g = c.getContext('2d');
    g.fillStyle = color;
    for (let i = 0; i < GW * GH; i++) if (bits[i] === '1') g.fillRect(i % GW, (i / GW) | 0, 1, 1);
    cache.set(key, c);
    return c;
  }

  G.textWidth = function (str, scale) {
    return str.length * ADV * (scale || 1) - (scale || 1);
  };

  // opts: scale, align ('left' | 'center' | 'right'), shadow (color)
